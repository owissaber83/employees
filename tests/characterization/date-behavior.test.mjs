// ║  الغرض توثيق «ما يفعله النظام اليوم» بالضبط، ليكون مرجع المقارنة يوم           ║
// ║  يُصلَح العيب في مرحلة مستقلة. إن انكسر هذا الاختبار فقد تغيّر سلوك التاريخ     ║
// ║  — وهو تغيير يجب أن يكون مقصوداً وموافَقاً عليه، لا عرضياً.                     ║
