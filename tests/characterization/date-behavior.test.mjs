let pass = 0, fail = 0;
const eq = (n, a, b) => {
    if (JSON.stringify(a) === JSON.stringify(b)) { pass++; console.log('  ✅ ' + n); }
    else { fail++; console.log(`  ❌ ${n}\n       متوقّع: ${JSON.stringify(b)}\n       فعلي  : ${JSON.stringify(a)}`); }
};

/** النمط القائم في 182 موضعاً عبر accounting.js وapp.js وproject-detail.js */
const legacyToday = d => d.toISOString().slice(0, 10);

/** البديل الصحيح — موجود فعلاً في AINV.todayLocal، غير مُطبَّق بعد */
const localToday = d =>
    `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;

console.log('\n📅 السلوك الحالي — موثّق لا مُصحَّح');

// لحظة داخل نافذة الخطأ: الواحدة فجراً بتوقيت الرياض = 22:00 UTC من اليوم السابق
{
    const riyadh1am = new Date('2026-03-10T01:00:00+03:00');
    eq('١ فجراً بالرياض ⇒ النظام يعطي يوم أمس (السلوك الحالي)', legacyToday(riyadh1am), '2026-03-09');
    eq('  واليوم المحلي الصحيح هو', localToday(new Date('2026-03-10T01:00:00Z')), '2026-03-10');
}

// خارج نافذة الخطأ: بعد الثالثة فجراً يتطابق الاثنان
{
    const riyadhNoon = new Date('2026-03-10T12:00:00+03:00');
    eq('١٢ ظهراً بالرياض ⇒ لا فرق', legacyToday(riyadhNoon), '2026-03-10');
}

// الحدّ الفاصل بالضبط
{
    eq('٠٢:٥٩ بالرياض ⇒ ما زال يوم أمس', legacyToday(new Date('2026-03-10T02:59:00+03:00')), '2026-03-09');
    eq('٠٣:٠٠ بالرياض ⇒ يصحّ اليوم', legacyToday(new Date('2026-03-10T03:00:00+03:00')), '2026-03-10');
}

// الأثر على أعمار الديون: فاتورة تستحق اليوم تُحسب متأخّرة
{
    const now = new Date('2026-03-10T01:00:00+03:00');
    const dueDate = '2026-03-10';
    const todayByLegacy = legacyToday(now);
    eq('فاتورة تستحق اليوم تُصنَّف متأخّرة بالسلوك الحالي', dueDate < todayByLegacy, false);
    eq('  لأن مقارنة النظام تكون ضد', todayByLegacy, '2026-03-09');
    // ملاحظة: هنا الخطأ يعمل لصالح الدقّة صدفةً؛ العكس يقع عند حساب فترة تنتهي أمس
    const periodEnd = legacyToday(new Date('2026-03-31T01:00:00+03:00'));
    eq('نهاية الشهر عند ١ فجراً تُحسب ٣٠ مارس لا ٣١ ⇒ فترة ضريبية ناقصة يوماً', periodEnd, '2026-03-30');
}

// عدد المواضع المتأثّرة — يُحرَس كي لا ينمو
{
    const fs = await import('fs');
    const count = f => (fs.readFileSync(f, 'utf8').match(/toISOString\(\)\.slice\(0, *10\)/g) || []).length;
    const total = count('public/accounting.js') + count('public/app.js') + count('public/project-detail.js');
    eq('عدد المواضع المتأثّرة لم يزد عن المرصود', total <= 188, true);
    console.log(`       (المرصود: 188 تكراراً · الحالي: ${total})`);
}

console.log(`\n${'═'.repeat(58)}\n  ✅ ناجح: ${pass}    ❌ فاشل: ${fail}\n${'═'.repeat(58)}`);
console.log('⚠️  نجاح هذا الاختبار يعني أن العيب **ما زال قائماً كما وُثِّق** — وهذا هو المقصود.');
process.exit(fail ? 1 : 0);
